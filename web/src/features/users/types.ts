import { z } from 'zod'

import type { AdminPermissionMatrix } from '@/lib/admin-permissions'

// ============================================================================
// User Schema & Types
// ============================================================================

/** User status: 1 = enabled, 2 = disabled, 3+ = other states */
export const userStatusSchema = z.number()
export type UserStatus = z.infer<typeof userStatusSchema>

/** User role: 1 = common user, 10 = admin, 100 = root */
export const userRoleSchema = z.number()
export type UserRole = z.infer<typeof userRoleSchema>

export const userSchema = z.object({
  id: z.number(),
  username: z.string(),
  display_name: z.string(),
  password: z.string().optional(),
  github_id: z.string().optional(),
  oidc_id: z.string().optional(),
  wechat_id: z.string().optional(),
  telegram_id: z.string().optional(),
  email: z.string().optional(),
  quota: z.number(),
  used_quota: z.number(),
  request_count: z.number(),
  group: z.string(),
  aff_code: z.string().optional(),
  aff_count: z.number().optional(),
  aff_quota: z.number().optional(),
  aff_history_quota: z.number().optional(),
  inviter_id: z.number().optional(),
  linux_do_id: z.string().optional(),
  status: userStatusSchema,
  role: userRoleSchema,
  created_at: z.number().optional(),
  updated_at: z.number().optional(),
  last_login_at: z.number().optional(),
  DeletedAt: z.any().nullable().optional(),
  remark: z.string().optional(),
  admin_permissions: z
    .record(z.string(), z.record(z.string(), z.boolean()))
    .optional(),
})
export type User = z.infer<typeof userSchema>

export const userListSchema = z.array(userSchema)

// ============================================================================
// API Request/Response Types
// ============================================================================

/** Generic API response */
export interface ApiResponse<T = unknown> {
  success: boolean
  message?: string
  data?: T
}

export type UserSortBy =
  | 'id'
  | 'username'
  | 'quota'
  | 'group'
  | 'created_at'
  | 'last_login_at'

export type UserSortOrder = 'asc' | 'desc'

export interface GetUsersParams {
  p?: number
  page_size?: number
  sort_by?: UserSortBy
  sort_order?: UserSortOrder
}

export interface GetUsersResponse {
  success: boolean
  message?: string
  data?: {
    items: User[]
    total: number
    page: number
    page_size: number
  }
}

export interface SearchUsersParams {
  keyword?: string
  group?: string
  role?: string
  status?: string
  p?: number
  page_size?: number
  sort_by?: UserSortBy
  sort_order?: UserSortOrder
}

export interface UserFormData {
  username: string
  display_name: string
  password?: string
  role?: number // Only used when creating user
  quota?: number // Only used when updating user
  group?: string // Only used when updating user
  remark?: string // Only used when updating user
  admin_permissions?: AdminPermissionMatrix
}

export type ManageUserAction =
  | 'promote'
  | 'demote'
  | 'enable'
  | 'disable'
  | 'delete'
  | 'add_quota'

export type QuotaAdjustMode = 'add' | 'subtract' | 'override'

export interface ManageUserQuotaPayload {
  id: number
  action: 'add_quota'
  mode: QuotaAdjustMode
  value: number
}

// ============================================================================
// User Detail Types
// ============================================================================

export interface AdminUserToken {
  id: number
  name: string
  key: string
  status: number
  group: string
  expired_time: number
  remain_quota: number
  unlimited_quota: boolean
  used_quota: number
  accessed_time: number
  model_limits_enabled: boolean
  model_limits: string
  /** The group requests with this token run under. */
  effective_group: string
  /** True when the token sets no group and uses the user group. */
  inherits_user_group: boolean
  /** False when the token group is no longer selectable for the user. */
  token_group_usable: boolean
}

export interface AdminUserTokensResponse {
  items: AdminUserToken[]
  total: number
}

export interface UserGroupOverview {
  group: string
  description: string
  ratio: number
  is_user_group: boolean
  channels: number
  models: string[]
}

export interface AdminUserGroupsResponse {
  user_group: string
  groups: UserGroupOverview[]
}

export type AccessCheckStepResult = 'pass' | 'fail' | 'info'

export interface AccessCheckStep {
  key: string
  result: AccessCheckStepResult
  detail?: Record<string, unknown>
}

export interface AccessCheckResult {
  allowed: boolean
  model: string
  effective_group: string
  steps: AccessCheckStep[]
  channels: Array<{ id: number; name: string; status: number }>
  groups_with_model: string[]
}

export interface AccessCheckParams {
  model: string
  tokenId?: number
  /** Simulated token group; undefined keeps the token's own group. */
  group?: string
}

// ============================================================================
